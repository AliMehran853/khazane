// ============================================================
// Helper: بازه‌ی فعلی بر اساس ساعت (پشتیبانی از wrap شبانه)
// ============================================================

export function getPeriodForHour(hour) {
  for (const p of GREETING_PERIODS) {
    const wraps = p.start > p.end;
    const inRange = wraps
      ? hour >= p.start || hour <= p.end
      : hour >= p.start && hour <= p.end;

    if (inRange) {
      return { ...p, messages: GREETINGS[p.id] || [] };
    }
  }
  return { ...GREETING_PERIODS[0], messages: GREETINGS.dawn };
}